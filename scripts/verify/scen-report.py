def node_html(sid, n, idx):
    img = embed(n.get('png'))
    page = n.get('page') or {}
    purl = page.get('url') or page.get('__error') or ''
    ptext = (page.get('text') or '').strip().replace('\n', ' / ')[:200]
    bar = (n.get('bar') or '').replace('\n', ' | ')
    return (
        '<div class="node">'
        '<div class="nodeHead"><span class="step">%d</span><span class="nlabel">%s</span>'
        '<span class="at">%s</span></div>'
        '<div class="nodeBody">'
        '<div class="shot">%s</div>'
        '<div class="side">'
        '<div class="kv"><b>测试条状态</b><div>%s</div></div>'
        '<div class="kv"><b>当前页面</b><div class="mono">%s</div><div class="dim">%s</div></div>'
        '</div></div></div>'
    ) % (idx + 1, esc(n.get('label')), esc(n.get('at')),
         ('<img src="%s">' % img) if img else '<div class="noshot">（截图缺失）</div>',
         esc(bar) or '（无）', esc(purl), esc(ptext))


def chat_html(txt):
    if not txt:
        return ''
    return '<div class="chat"><b>聊天窗口里 AI 说的话（尾部）</b><div>%s</div></div>' % nl(txt)


def chat_delta(results, i):
    """聊天窗口是**累积**的（每场都带着上一场的话），直接贴会看不出这场到底说了什么。
    取法：这一场的尾部文本 减去 上一场的尾部文本（追加式，前缀相同）。"""
    cur = (results[i].get('chat_after') or '').strip()
    if i == 0:
        return cur
    prev = (results[i - 1].get('chat_after') or '').strip()
    if prev and cur.startswith(prev):
        return cur[len(prev):].strip()
    # 对不上就直接从「本场目标」那句之后开始截，至少别把上一场的尾巴带进来
    return cur[-600:]


